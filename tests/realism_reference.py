"""Reference outputs of the P centre for the realism-options regression test.

The P centre (00-common section 7 of the v0.2 plan: diffusive coupling 0.6 on a trap
lattice, non-negative input with positive weights, kinetic heterogeneity 0.065,
warm-up 800, 16 substeps) on an 8 x 8 lattice drives five synthetic beats
(``regression_reference.synthetic_beats``). ``tests/unit/test_realism_regression.py``
checks that the reservoir reproduces the state trajectories and the features of
``training.simulate`` with the realism options absent and at zero.

The reference was generated by the code before the realism options (commit 3fe2091).
Regenerate it only for an intended change, with a ``[science]`` CHANGELOG entry::

    python tests/realism_reference.py --write
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

REFERENCE = Path(__file__).resolve().parent / "data" / "regression" / "p-centre-model.npz"
SEED = 6337
P_CENTRE = {
    "reservoir_type": "bioreservoir", "units": 64, "warmup": 800, "rk4_substeps": 16,
    "input_scaling": 0.155113, "input_connectivity": 0.66, "input_bias": False,
    "bias_scaling": 0.1, "rc_scaling": 0.007036187544739917,
    "dde_scaling": 0.0006439480590749527, "cell_coupling": 12.74579065885262,
    "noise_in": 0.01442, "noise_rc": 0.2397, "output_variables": "IHe",
    "param_heterogeneity_cv": 0.065, "param_heterogeneity_seed": 7,
    "heterogeneity_mean_preserving": True, "topology_type": "lattice",
    "geometry": "per_node", "delay_scheme": "substep", "coupling": "diffusion",
    "diffusion_rate": 0.6, "input_encoding": "nonnegative", "input_sign": "positive",
}


def p_centre_outputs(**options) -> dict[str, np.ndarray]:
    """State trajectories (every 17th step), final states and simulated features."""
    from regression_reference import synthetic_beats

    from optimization.reservoirs import build_reservoir
    from training.simulate import simulate_beats

    params = dict(P_CENTRE, **options)
    X = synthetic_beats()
    reservoir, _ = build_reservoir(params, seed=SEED)
    trajectories = np.stack([reservoir.run(x, reset=True) for x in X])
    reservoir, _ = build_reservoir(params, seed=SEED)
    features = simulate_beats(reservoir, X, noise_seed=SEED, aggregation="mean")
    return {"trajectory": trajectories[:, ::17], "final": trajectories[:, -1],
            "features": features}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help=f"Write {REFERENCE.name}.")
    args = parser.parse_args()
    outputs = p_centre_outputs()
    if args.write:
        REFERENCE.parent.mkdir(parents=True, exist_ok=True)
        np.savez_compressed(REFERENCE, **outputs)
        print(f"wrote {REFERENCE}")
    for key, value in outputs.items():
        print(key, value.shape, float(np.abs(value).mean()))


if __name__ == "__main__":
    main()
