"""Tables S13-S15 against the archived Phase 4 databases.

The rows (best trial of each classifier family) are generated by
``scripts/analysis/readout_tables.py`` from the canonical v0.1 databases and compared with
a stored snapshot, so the tables cannot drift from the archive again.
"""

import importlib.util
import json
from pathlib import Path

import pytest

from utils import config

ROOT = Path(__file__).resolve().parents[2]
SNAPSHOT = Path(__file__).with_name("snapshots") / "readout_tables_v0.1.json"


def _tables():
    spec = importlib.util.spec_from_file_location(
        "readout_tables", ROOT / "scripts" / "analysis" / "readout_tables.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_readout_tables_match_the_archive_snapshot():
    tables = _tables()
    if not all(config.optuna_db(name, "v0.1").is_file() for name in tables.STUDIES):
        pytest.skip("archive not available")
    assert tables.summary("v0.1") == json.loads(SNAPSHOT.read_text())


def test_the_headline_readouts_head_their_tables():
    snapshot = json.loads(SNAPSHOT.read_text())
    best = {name: table["rows"][0] for name, table in snapshot.items()}
    assert {name: (row["classifier"], row["trial"]) for name, row in best.items()} == {
        "P4-readout-balanced": ("RF", 833),
        "P4-readout-unbalanced": ("RF", 604),
        "P4-readout-binary": ("RF", 651),
    }
